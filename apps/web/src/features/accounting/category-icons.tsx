/** 未知历史图标仍保留原值，仅在 Web 展示中回落为通用分类图标。 */
export function CategoryIcon({ name, size = 18 }: { name: string | null; size?: number }) {
  const Icon = name && Object.hasOwn(categoryIcons, name) ? categoryIcons[name as keyof typeof categoryIcons] : Shapes;
  return <Icon size={size} aria-hidden />;
}
