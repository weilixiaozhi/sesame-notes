import { ApiError } from '@sesame-notes/api-client';
import { beforeEach, describe, expect, it, vi, type Mock } from 'vitest';
import { api, captureSessionOperation, queryClient } from '../../../lib/session';
import type { FitnessPlan, FitnessSpace } from '../fitness-model';
import { newPlanDraft } from './plan-model';
import { refreshFitnessSchedule } from './refresh-plan-schedule';

vi.mock('../../../lib/session', () => ({
  api: { GET: vi.fn(), POST: vi.fn() },
  captureSessionOperation: vi.fn(),
  queryClient: { invalidateQueries: vi.fn().mockResolvedValue(undefined) },
}));
const get = api.GET as unknown as Mock<(path: string, options?: unknown) => Promise<unknown>>;
const post = api.POST as unknown as Mock<(path: string, options?: unknown) => Promise<unknown>>;
const now = '2026-09-30T10:00:00.000Z';
const today = '2026-09-30';
const space: FitnessSpace = {
  id: 'space',
  sync_id: 'sync',
  revision: 1,
  entity_count: 0,
  name: '测试空间',
  created_at: now,
  updated_at: now,
  deleted_at: null,
};

/** 构造真实生成契约的计划，只变更待测游标与状态。 */
function plan(
  id: string,
  next: string | null,
  status: FitnessPlan['status'] = 'in_progress',
  revision = 1,
): FitnessPlan {
  const payload = newPlanDraft(undefined, today, now).payload;
  return {
    ...payload,
    id,
    fitness_space_id: space.id,
    sync_id: space.sync_id,
    revision,
    deleted_at: null,
    status,
    generation_state: { ...payload.generation_state, next_cycle_start_date: next },
  };
}

beforeEach(() => {
  vi.clearAllMocks();
  get.mockReset();
  post.mockReset().mockResolvedValue({ data: { has_more: false } });
  vi.mocked(captureSessionOperation).mockReturnValue({
    client: api,
    signal: new AbortController().signal,
    assertCurrent: vi.fn(),
    invalidate: vi.fn(),
  });
});

describe('automatic fitness schedule refresh', () => {
  it('reads every page and writes only due active plans, including an ungenerated first cycle', async () => {
    get.mockResolvedValueOnce({
      data: { items: [plan('closed', today, 'closed'), plan('future', '2026-10-01')], next_cursor: 'page2' },
    });
    get.mockResolvedValueOnce({ data: { items: [plan('due', today), plan('new', null)], next_cursor: null } });
    await expect(refreshFitnessSchedule(space, 'user', new Map(), today)).resolves.toEqual({ hasMore: false });
    expect(get.mock.calls[1]![1]).toMatchObject({ params: { query: { cursor: 'page2', sync_id: 'sync' } } });
    expect(post.mock.calls.map(([, options]) => options)).toMatchObject([
      { params: { path: { plan_id: 'due' } }, body: { action: 'generate', today, base_revision: 1 } },
      { params: { path: { plan_id: 'new' } }, body: { action: 'generate', today, base_revision: 1 } },
    ]);
    expect(queryClient.invalidateQueries).toHaveBeenCalledExactlyOnceWith({
      queryKey: ['account', 'user', 'fitness', 'space'],
    });
  });

  it('does not invalidate or loop when no active cycle is due', async () => {
    get.mockResolvedValue({ data: { items: [plan('future', '2026-10-01')], next_cursor: null } });
    await refreshFitnessSchedule(space, 'user', new Map(), today);
    expect(post).not.toHaveBeenCalled();
    expect(queryClient.invalidateQueries).not.toHaveBeenCalled();
  });

  it('rereads a concurrent version and avoids overwriting a cycle already generated by another device', async () => {
    get.mockResolvedValueOnce({ data: { items: [plan('due', today)], next_cursor: null } });
    get.mockResolvedValueOnce({ data: { items: [plan('due', '2026-10-07', 'in_progress', 2)], next_cursor: null } });
    post.mockRejectedValueOnce(new ApiError(409, 'FITNESS_PLAN_CHANGED', '版本冲突'));
    const attempts = new Map();
    await refreshFitnessSchedule(space, 'user', attempts, today);
    expect(post).toHaveBeenCalledTimes(1);
    expect(get).toHaveBeenCalledTimes(2);
    expect(attempts.size).toBe(0);
  });

  it('preserves the exact command on an uncertain network retry and reports remaining batches', async () => {
    get.mockResolvedValue({ data: { items: [plan('due', today)], next_cursor: null } });
    post.mockRejectedValueOnce(new TypeError('offline')).mockResolvedValueOnce({ data: { has_more: true } });
    const attempts = new Map();
    await expect(refreshFitnessSchedule(space, 'user', attempts, today)).rejects.toThrow('offline');
    expect(attempts.size).toBe(1);
    await expect(refreshFitnessSchedule(space, 'user', attempts, today)).resolves.toEqual({ hasMore: true });
    expect(post.mock.calls[1]![1]).toEqual(post.mock.calls[0]![1]);
    expect(attempts.size).toBe(0);
  });

  it('refreshes successfully changed data even if a later plan fails', async () => {
    get.mockResolvedValue({ data: { items: [plan('first', today), plan('second', today)], next_cursor: null } });
    post.mockResolvedValueOnce({ data: { has_more: false } }).mockRejectedValueOnce(new TypeError('offline'));
    await expect(refreshFitnessSchedule(space, 'user', new Map(), today)).rejects.toThrow('offline');
    expect(queryClient.invalidateQueries).toHaveBeenCalledTimes(1);
  });

  it.each(['SESSION_CHANGED', 'ENTITY_SCOPE_CONFLICT'])('does not retry a non-version conflict: %s', async (code) => {
    get.mockResolvedValue({ data: { items: [plan('due', today)], next_cursor: null } });
    const failure = new ApiError(409, code, '不能继续当前操作');
    post.mockRejectedValueOnce(failure);
    await expect(refreshFitnessSchedule(space, 'user', new Map(), today)).rejects.toBe(failure);
    expect(get).toHaveBeenCalledTimes(1);
    expect(post).toHaveBeenCalledTimes(1);
    expect(queryClient.invalidateQueries).not.toHaveBeenCalled();
  });

  it('stops pagination when the captured session expires instead of requesting the next page as the new account', async () => {
    let current = true;
    const failure = new ApiError(409, 'SESSION_CHANGED', '账号已切换');
    vi.mocked(captureSessionOperation).mockReturnValue({
      client: api,
      signal: new AbortController().signal,
      assertCurrent: () => {
        if (!current) throw failure;
      },
      invalidate: vi.fn(),
    });
    get.mockImplementationOnce(async () => {
      current = false;
      return { data: { items: [plan('due', today)], next_cursor: 'another-page' } };
    });
    await expect(refreshFitnessSchedule(space, 'user', new Map(), today)).rejects.toBe(failure);
    expect(get).toHaveBeenCalledTimes(1);
    expect(post).not.toHaveBeenCalled();
  });

  it('stops remaining plans and cache effects after a response crosses the captured session boundary', async () => {
    let current = true;
    const controller = new AbortController();
    const failure = new ApiError(409, 'SESSION_CHANGED', '账号已切换');
    vi.mocked(captureSessionOperation).mockReturnValue({
      client: api,
      signal: controller.signal,
      assertCurrent: () => {
        if (!current) throw failure;
      },
      invalidate: vi.fn(),
    });
    get.mockResolvedValue({ data: { items: [plan('first', today), plan('second', today)], next_cursor: null } });
    post.mockImplementationOnce(async () => {
      current = false;
      controller.abort(failure);
      return { data: { has_more: false } };
    });
    await expect(refreshFitnessSchedule(space, 'user', new Map(), today)).rejects.toBe(failure);
    expect(captureSessionOperation).toHaveBeenCalledTimes(1);
    expect(get).toHaveBeenCalledTimes(1);
    expect(post).toHaveBeenCalledTimes(1);
    expect(queryClient.invalidateQueries).not.toHaveBeenCalled();
  });
});
